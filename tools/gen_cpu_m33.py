"""src/cpu6510_m33.pico2: the 6510 for the RP2350 (Cortex-M33), from tools/gen_cpu.py's opcode table.

The handlers are cpu6510.pmi's, with the two things every instruction does written in Thumb-2:

  the tail     count the instruction, stop at the end of the budget, fetch the next opcode through the
               page table and jump through the dispatch table (one `ldr pc, [table, op, lsl #2]`);
  a fetch      each operand byte read from PC.

A fetch from an I/O page (Pg = 0) takes the PureMetal path, so its AccessPhase and C64IoRead are the same
as before. Registers: r8 = PC, r5 = Pg, r11 = Left (ReserveRegister, as in cpu6510.pmi); a block uses
r0-r2 besides, and lr only through its bl. The RP2040 keeps cpu6510.pmi (Thumb-1, no Thumb-2 here).

Run after tools/gen_cpu.py:   py -3 tools/gen_cpu_m33.py
"""
import importlib.util
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location('gen_cpu', ROOT / 'tools' / 'gen_cpu.py')
g = importlib.util.module_from_spec(spec)
spec.loader.exec_module(g)

TAIL = '''  ASM Uses Left, PC, Pg
    subs r11, r11, #{c}
    ldr r1, =global_cpuinstructions
    ldr r2, [r1]
    add.w r2, r2, #1
    str r2, [r1]
    ble __ul_cpurun_done
    lsr r1, r8, #8
    ldr r2, =global_rdmap
    ldr r5, [r2, r1, lsl #2]
    cmp r5, #0
    beq __ul_cpurun_slowfetch
    ldrb r0, [r5, r8]
    add r8, r8, #1
    ubfx r8, r8, #0, #16
    ldr r1, =global_dispatch
    ldr pc, [r1, r0, lsl #2]
  EndASM'''

FETCH = '''  ASM Uses PC, Pg
    lsr r1, r8, #8
    ldr r2, =global_rdmap
    ldr r5, [r2, r1, lsl #2]
    cbz r5, {lab}_io
    ldrb r0, [r5, r8]
    b {lab}_got
  {lab}_io:
    movs r0, #{ph}
    ldr r1, =global_accessphase
    str r0, [r1]
    mov r0, r8
    bl c64ioread
  {lab}_got:
    ldr r1, =global_{dst}
    str r0, [r1]
    add r8, r8, #1
    ubfx r8, r8, #0, #16
  EndASM'''

FETCH_RE = re.compile(
    r'  Pg = RdMap\(PC >> 8\)\n'
    r'  If Pg : (\w+) = PeekA\(Pg \+ PC\) : Else : AccessPhase = (\d) : \1 = C64IoRead\(PC\) : EndIf\n'
    r'  PC = \(PC \+ 1\) & \$FFFF\n')


def handler(code, lines):
    text = '\n'.join(lines) + '\n'
    n = [0]

    def fetch(m):
        n[0] += 1
        return FETCH.format(lab=f'op{code:02x}f{n[0]}', ph=m[2], dst=m[1].lower()) + '\n'

    text = FETCH_RE.sub(fetch, text)
    text = re.sub(r'  CpuNextOp\((\d+)\)', lambda m: TAIL.format(c=m[1]), text)
    return text.rstrip('\n').split('\n')


def generate():
    out = []
    for code in range(256):
        mn, mode, cyc, pen = g.T[code]
        out.append(f'Op{code:02X}: ; ${code:02X} {mn} {mode}')
        out += handler(code, g.body(code))
    table = '\n'.join(f'    Dispatch(${c:02X}) = ?Op{c:02X}' for c in range(256))
    head = g.HEAD.replace('{LABEL}', 'Label').replace('{PROC}', 'ProcedureRAM').replace(
        '{GOTO}', 'Goto Dispatch(Tmp)').replace(
        '{RESERVE}', 'ReserveRegister PC = r8, A = r9, Res = r10, Left = r11, X = r4, Pg = r5\n')
    head = head.replace(
        '; GENERATED by tools/gen_cpu.py - do not edit; regenerate.',
        '; GENERATED by tools/gen_cpu_m33.py - do not edit; regenerate.\n'
        '; THE RP2350 (Cortex-M33) CORE: cpu6510.pmi\'s handlers with the tail and the operand fetches\n'
        '; in Thumb-2 (tools/gen_cpu_m33.py says how). RP2350 builds only.', 1)
    assert 'Global Dim Dispatch.Label(256)\n' in head and '    Ready = 1\n' in head
    head = head.replace('Global Dim Dispatch.Label(256)\n',
                        'Global Dim Dispatch.Label(256)\nGlobal SlowFetchAt.Label\n', 1)
    # the slow path is reached only from the Thumb-2 tails: its address taken keeps it in the image
    head = head.replace('    Ready = 1\n', '    SlowFetchAt = ?SlowFetch\n    Ready = 1\n', 1)
    foot = ('; the next opcode from an I/O page (the Thumb-2 tail\'s slow path)\n'
            'SlowFetch:\n'
            '  AccessPhase = 0 : Tmp = C64IoRead(PC)\n'
            '  PC = (PC + 1) & $FFFF\n'
            '  Goto Dispatch(Tmp)\n') + g.FOOT
    return head.replace('{TABLE}', table) + '\n'.join(out) + '\n' + foot


if __name__ == '__main__':
    s = generate()
    (ROOT / 'src' / 'cpu6510_m33.pico2').write_text(s, newline='\n')
    print('generated: src/cpu6510_m33.pico2,', s.count('  ASM Uses'), 'Thumb-2 blocks')
