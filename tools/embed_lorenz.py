"""Split Wolfgang Lorenz's CPU test chain into batches that fit a Pico image and
write one wrapper per batch: src/tests/lorenzN.picow (and .pico2w).

The chain order is the suite's own (each test loads the next by name); it is read
from docs/lorenz-desktop.log, the desktop core's run. Each record in the data is
  name length, name (PETSCII lower case = ASCII), size lo, size hi, the PRG bytes
and a 0 length ends the list. A batch stops when the chain asks for a test
it does not hold, and prints that name, so the next batch starts there.
"""
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
log = (ROOT / 'docs' / 'lorenz-desktop.log').read_text().splitlines()
names = [l for l in log if l and ' - ok' not in l and l.replace('(', '').replace(')', '').isalnum() and l.islower()]
chain = [' start'] + [n for n in names if n != 'trap17']
LIMIT = 100_000
batches, cur, size = [], [], 0
for n in chain:
    b = (ROOT / 'tests' / 'lorenz' / n).read_bytes()
    if cur and size + len(b) > LIMIT:
        batches.append(cur); cur, size = [], 0
    cur.append((n, b)); size += len(b) + len(n) + 3
batches.append(cur)
for i, batch in enumerate(batches, 1):
    lines = [f'; GENERATED by tools/embed_lorenz.py - batch {i} of {len(batches)}: {batch[0][0].strip()} .. {batch[-1][0]}',
             'DataSection', 'LorenzFirst:']
    lines.append('  Data.a ' + ','.join(f'${c:02X}' for c in batch[0][0].encode()) + ',0')
    lines.append('LorenzData:')
    for n, b in batch:
        rec = bytes([len(n)]) + n.encode() + bytes([len(b) & 255, len(b) >> 8]) + b
        for s in range(0, len(rec), 32):
            lines.append('  Data.a ' + ','.join(f'${c:02X}' for c in rec[s:s + 32]))
    lines.append('  Data.a 0')
    lines.append('EndDataSection')
    (ROOT / 'src' / 'tests' / f'lorenz_data{i}.pico').write_text('\n'.join(lines) + '\n', newline='\n')
    for ext, lib in (('picow', 'RP2040'), ('pico2w', 'RP2350')):
        (ROOT / 'src' / 'tests' / f'lorenz{i}.{ext}').write_text(
            f'; GENERATED by tools/embed_lorenz.py: Lorenz CPU tests, batch {i} of {len(batches)}.\n'
            f'#LORENZ_BATCH = {i}\n#LORENZ_BATCHES = {len(batches)}\nEnableExplicit\n'
            f'XIncludeFile "../platform_{lib.lower()}.pico"\nXIncludeFile "../cpu6510.pico"\n'
            f'XIncludeFile "lorenz_data{i}.pico"\nXIncludeFile "../lorenz_bench.pico"\nLorenzMain()\n', newline='\n')
print(len(chain), 'tests in', len(batches), 'batches:', [len(b) for b in batches])
