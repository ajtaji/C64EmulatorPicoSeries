"""Turn the board's machine sources (src/*.pmi) into the desktop's PureBasic
(desktop/core/*.pbi). The sources are written in the subset the two compilers
share, so the port is small: ProcedureRAM becomes Procedure. The CPU comes
from tools/gen_cpu.py, which writes both versions itself."""
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
FILES = ['c64', 'cia', 'vic', 'sid', 'bench', 'loader']
out = ROOT / 'desktop' / 'core'
out.mkdir(parents=True, exist_ok=True)
for name in FILES:
    s = (ROOT / 'src' / f'{name}.pmi').read_text()
    s = s.replace('ProcedureRAM', 'Procedure')
    head = f'; GENERATED by tools/port_desktop.py from src/{name}.pmi - do not edit; regenerate.\n'
    (out / f'{name}.pbi').write_text(head + s, newline='\n')
(out / 'machine.pbi').write_text(
    '; GENERATED by tools/port_desktop.py: the whole machine, in include order.\n' +
    'XIncludeFile "cpu6510.pbi"\n' + ''.join(f'XIncludeFile "{n}.pbi"\n' for n in FILES), newline='\n')
print('ported', len(FILES), 'files')
